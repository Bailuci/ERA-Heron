test('det_math 与 fdlibm 金标准逐位一致', () => {
  const det = create_host().load_src('utils/det_math');
  let count = 0;
  for (const [name, rows] of Object.entries(GOLDEN)) {
    for (const row of rows) {
      const args = row.slice(0, -1);
      const want = row[row.length - 1];
      assert.equal(bits(det[name](...args)), want, `${name}(${args.join(', ')})`);
      count++;
    }
  }
  assert.ok(count > 400);
});

test('det_math：10 和 2 的整数次幂取对数得到精确的整数', () => {
  const det = create_host().load_src('utils/det_math');
  for (let k = -20; k <= 22; k++) assert.equal(det.log10(Number(`1e${k}`)), k, `log10(1e${k})`);
  for (let k = -1074; k <= 1023; k++) assert.equal(det.log2(2 ** k), k, `log2(2^${k})`);
  assert.equal(det.pow(2, 10), 1024);
  assert.equal(det.pow(10, 3), 1000);
  assert.equal(det.pow(0, 0), 1);
  assert.equal(det.log(1), 0);
  assert.equal(det.exp(0), 1);
});

test('det_math：detMath 集合包含全部函数，且被冻结', () => {
  const { detMath } = create_host().load_src('utils/det_math');
  for (const name of [...Object.keys(GOLDEN), 'sqrt', 'abs', 'floor', 'ceil', 'trunc', 'round', 'sign', 'min', 'max']) {
    assert.equal(typeof detMath[name], 'function', name);
  }
  assert.equal(detMath.PI, Math.PI);
  assert.equal(detMath.E, Math.E);
  assert.ok(Object.isFrozen(detMath));
});

test('det_math 源码不使用引擎近似实现的原生函数', () => {
  const source = fs.readFileSync(path.join(__dirname, '..', 'src', 'ERA变量框架', 'utils', 'det_math.ts'), 'utf8');
  const code = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
  const used = [...code.matchAll(/Math\.(\w+)/g)].map(match => match[1]);
  const allowed = new Set(['sqrt', 'abs', 'floor', 'ceil', 'trunc', 'round', 'sign', 'min', 'max', 'imul', 'PI', 'E']);
  assert.deepEqual(
    used.filter(name => !allowed.has(name)),
    [],
  );
  assert.ok(!code.includes('**'), '不能使用 ** 运算符');
});
